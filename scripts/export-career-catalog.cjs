// Export the existing TypeScript catalog for server-side profile adaptation.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const ts = require(path.join(root, 'web/node_modules/typescript'));
require.extensions['.ts'] = (module, filename) => {
  const output = ts.transpileModule(fs.readFileSync(filename, 'utf8'), {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 },
  });
  module._compile(output.outputText, filename);
};
const dataDir = path.join(root, 'web/src/lib/data');
const evidence = require(path.join(root, 'api/app/career/evidence.json'));
const campusFile = path.join(dataDir, 'campusNodes.ts');
// Keep previously issued event IDs resolvable for students who recorded attendance.
const prior = fs.existsSync(campusFile) ? require(campusFile).CAMPUS_NODES : [];
const campus = new Map(prior.map(node => [node.id, node]));
for (const activity of evidence.activities) {
  if (activity.eligibility_status !== 'reviewed' || !activity.outcome || !activity.source_url) continue;
  const id = 'ACT-' + activity.id;
  campus.set(id, { id, name: activity.title, url: activity.source_url });
}
const ordered = [...campus.values()].sort((a, b) => a.id.localeCompare(b.id, 'en'));
const source = '// Generated by scripts/export-career-catalog.cjs from reviewed public activities.\n'
  + 'export const CAMPUS_NODES = ' + JSON.stringify(ordered, null, 2) + ';\n';
fs.writeFileSync(campusFile, source);
delete require.cache[campusFile];
const { POSTING_PROJECTS } = require(path.join(dataDir, 'postingProjects.ts'));
const postingProjectPatterns = Object.fromEntries(POSTING_PROJECTS.map(entry => [entry.id, entry.pattern]));
const { DEPARTMENTS } = require(path.join(root, 'web/src/lib/data/departments.ts'));
const { JOBS, SKILLS, SCALES } = require(path.join(root, 'web/src/lib/data/catalog.ts'));
fs.writeFileSync(path.join(root, 'api/app/career/web_catalog.json'),
  JSON.stringify({ departments: DEPARTMENTS, jobs: JOBS, skills: SKILLS, scales: SCALES, postingProjectPatterns }, null, 2));
console.log(JSON.stringify({ departments: DEPARTMENTS.length, jobs: JOBS.length, skills: SKILLS.length }));
